// Writes public/third-party-licenses.txt: every production dependency with its licence and full licence text.
import { execSync } from 'node:child_process';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
const dirs = execSync('npm ls --omit=dev --all --parseable', { encoding: 'utf8' }).trim().split('\n').slice(1);
const seen = new Set(), out = ['Prvlar — third-party software licences', 'Generated by scripts/gen-licenses.mjs from the production dependencies.', ''];
const FIX = { khroma: 'MIT' };
for (const d of dirs.sort()) {
  let p; try { p = JSON.parse(readFileSync(join(d, 'package.json'), 'utf8')); } catch { continue; }
  const id = p.name + '@' + p.version; if (seen.has(id)) continue; seen.add(id);
  const lic = p.license || (p.licenses || []).map(l => l.type || l).join(' OR ') || FIX[p.name] || 'see package';
  const f = readdirSync(d).find(x => /^(licen[cs]e|copying|notice)(\.|$)/i.test(x));
  out.push('='.repeat(72), `${id}  —  ${FIX[p.name] && !p.license ? FIX[p.name] : lic}`, p.homepage || (p.repository?.url || p.repository || ''), '');
  if (f) out.push(readFileSync(join(d, f), 'utf8').trim(), '');
}
out.push('='.repeat(72), 'Pyodide (bundled under pyodide/) — MPL-2.0; includes CPython (Python Software Foundation License 2.0). https://pyodide.org  https://docs.python.org/3/license.html', '');
writeFileSync('public/third-party-licenses.txt', out.join('\n'));
console.log(seen.size, 'packages');
